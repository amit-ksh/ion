//! Assignment documents are effects: authorize the lease and commit the payload,
//! artifact provenance and exact tool receipt in one transaction.
use super::*;

impl TeamCoordinator {
    pub(crate) fn read_source_document(
        &self,
        source: Uuid,
        project: Uuid,
        run: Uuid,
        artifact: Uuid,
    ) -> Result<Vec<u8>> {
        let db = self.connect()?;
        let run = load(&db, run)?;
        ensure!(
            run.project_id == project && run.origin.as_ref().is_some_and(|o| o.task_id == source),
            "Team result belongs to another source task/project"
        );
        ensure!(
            run.status == TeamRunStatus::Completed,
            "Wait for the team to complete before using its document evidence"
        );
        let (work,content):(String,Vec<u8>)=db.query_row("SELECT d.work_id,d.content FROM ion_team_document_receipts d JOIN ion_team_work w ON w.id=d.work_id WHERE d.artifact_id=? AND w.run_id=? AND length(d.content) BETWEEN 1 AND 65536 AND EXISTS(SELECT 1 FROM ion_control_records r WHERE r.id=d.artifact_id AND r.kind='artifact')",params![artifact.to_string(),run.id.to_string()],|r|Ok((r.get(0)?,r.get(1)?))).context("Document was not generated by this team run")?;
        ensure!(
            run.work
                .iter()
                .any(|w| w.id.to_string() == work && w.status == AssignmentStatus::Completed),
            "Superseded or unaccepted team documents cannot be used"
        );
        ensure!(
            content.len() <= 64 * 1024,
            "Team document exceeds its bound"
        );
        let verified = self.control.read_document(artifact)?;
        ensure!(verified == content, "Document changed during source read");
        Ok(verified)
    }

    pub fn publish_document(
        &self,
        lease: &AssignmentLease,
        request_id: Uuid,
        name: &str,
        format: &str,
        content: &str,
        now: u64,
    ) -> Result<Artifact> {
        let mut db = self.connect()?;
        let tx = db.transaction_with_behavior(TransactionBehavior::Immediate)?;
        let run = load(&tx, lease.run_id)?;
        active(&run, now)?;
        let work = checked_lease(&run, lease, now, false)?;
        let artifact =
            publish_in_transaction(&tx, &run, work, request_id, name, format, content, now)?;
        tx.commit()?;
        Ok(artifact)
    }

    pub fn read_assignment_document(
        &self,
        lease: &AssignmentLease,
        id: Uuid,
        now: u64,
    ) -> Result<Vec<u8>> {
        let mut db = self.connect()?;
        let tx = db.transaction()?;
        let run = load(&tx, lease.run_id)?;
        active(&run, now)?;
        let work = checked_lease(&run, lease, now, false)?;
        validate_result(
            &tx,
            &run,
            work,
            &AssignmentResult {
                executed_checks: vec![],
                summary: "Read assignment document".into(),
                artifact_ids: vec![id],
                checks: vec![],
            },
        )?;
        tx.commit()?;
        self.control.read_document(id)
    }
}

/// Trusted host recovery and the live adapter share the same atomic provenance.
pub(super) fn publish_in_transaction(
    tx: &Transaction<'_>,
    run: &TeamRunSnapshot,
    work: &TeamAssignment,
    request_id: Uuid,
    name: &str,
    format: &str,
    content: &str,
    now: u64,
) -> Result<Artifact> {
    text(name, 160, "Document name")?;
    ensure!(
        !name.contains(['/', '\\', ':']) && name != "." && name != "..",
        "Use a document filename without directories"
    );
    ensure!(
        matches!(format, "html" | "md" | "txt" | "csv" | "json"),
        "Unsupported generated document format"
    );
    text(content, 64 * 1024, "Document content")?;
    let previous: Option<(String,String,String,Vec<u8>)> = tx.query_row(
            "SELECT artifact_id,name,format,content FROM ion_team_document_receipts WHERE work_id=? AND request_id=? AND length(content) BETWEEN 1 AND 65536",
            params![work.id.to_string(),request_id.to_string()], |r| Ok((r.get(0)?,r.get(1)?,r.get(2)?,r.get(3)?)),
        ).optional()?;
    if let Some((id, stored_name, stored_format, bytes)) = previous {
        ensure!(
            stored_name == name && stored_format == format && bytes == content.as_bytes(),
            "Document replay arguments changed"
        );
        let body: String = tx
            .query_row(
                "SELECT body FROM ion_control_records WHERE id=? AND kind='artifact'",
                [id],
                |r| r.get(0),
            )
            .context("Published document was removed")?;
        let ControlRecord::Artifact(artifact) = serde_json::from_str(&body)? else {
            anyhow::bail!("Document identity changed")
        };
        ensure!(
            artifact.task_id == Some(work.task_id) && artifact.project_id == Some(run.project_id),
            "Published document provenance changed"
        );
        ensure!(
            artifact.evidence.as_ref().is_none_or(|e| e.matches(&bytes)
                && e.producer.origin == ArtifactOrigin::TeamAssignment
                && e.producer.run_id == Some(run.id)
                && e.producer.assignment_id == Some(work.id)
                && e.producer.agent_id == Some(work.agent_id)
                && e.producer.request_id == Some(request_id)),
            "Published document evidence changed"
        );
        return Ok(artifact);
    }
    let count: u32 = tx.query_row("SELECT count(*) FROM ion_control_records", [], |r| r.get(0))?;
    ensure!(count < 1000, "Workspace document library is full");
    let id = Uuid::new_v4();
    let artifact = Artifact {
        id,
        name: name.into(),
        format: format.into(),
        project_id: Some(run.project_id),
        task_id: Some(work.task_id),
        reference: format!("ion-document:{id}"),
        created_at: now,
        evidence: Some(ArtifactEvidence::from_bytes(
            content.as_bytes(),
            ArtifactProvenance {
                origin: ArtifactOrigin::TeamAssignment,
                run_id: Some(run.id),
                assignment_id: Some(work.id),
                agent_id: Some(work.agent_id),
                request_id: Some(request_id),
                ..Default::default()
            },
        )),
    };
    tx.execute(
        "INSERT INTO ion_control_records VALUES(?,?,?)",
        params![
            id.to_string(),
            "artifact",
            serde_json::to_string(&ControlRecord::Artifact(artifact.clone()))?
        ],
    )?;
    tx.execute(
        "INSERT INTO ion_team_document_receipts VALUES(?,?,?,?,?,?)",
        params![
            work.id.to_string(),
            request_id.to_string(),
            id.to_string(),
            name,
            format,
            content.as_bytes()
        ],
    )?;
    tx.execute(
        "UPDATE ion_control_revision SET revision=revision+1 WHERE id=1",
        [],
    )?;
    bump(tx, run.id)?;
    audit(
        tx,
        run.id,
        Some(work.id),
        "document",
        &format!("Published {id}"),
        now,
    )?;
    Ok(artifact)
}
